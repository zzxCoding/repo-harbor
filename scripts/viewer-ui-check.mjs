import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const info = JSON.parse(await fs.readFile(process.env.UI_INFO_PATH || '/tmp/code-atlas-ui-info.json', 'utf8'));
const evidence = new URL('../test/evidence/', import.meta.url);
const prefix = process.env.VIEWER_EVIDENCE_PREFIX || 'map';
await fs.mkdir(evidence, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--enable-unsafe-swiftshader'] });
const errors = [], externalRequests = [], checks = [];
try {
  const context = await browser.newContext({ viewport: { width: 1600, height: 1000 } });
  context.on('page', page => page.on('pageerror', error => errors.push(error.message)));
  context.on('request', request => { if (new URL(request.url()).origin !== new URL(info.baseUrl).origin) externalRequests.push(request.url()); });
  const page = await context.newPage();
  await page.goto(info.baseUrl);
  await page.locator('#login-password').fill(process.env.ADMIN_TEST_PASSWORD || 'fixture-admin-password');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await page.waitForFunction(() => /[a-f0-9]{12}/.test(document.querySelector('#repo-rows .commit')?.textContent || ''), { timeout: 45000 });
  await page.getByRole('button', { name: '详情', exact: true }).first().click();
  await page.waitForFunction(() => !document.getElementById('detail-map').disabled);
  const popup = context.waitForEvent('page');
  await page.getByRole('button', { name: '查看地图', exact: true }).click();
  const map = await popup; await map.waitForLoadState();
  await map.locator('#map-workspace').waitFor({ state: 'visible', timeout: 45000 });
  const commit = await map.locator('#repo-version').getAttribute('data-commit');
  assert.match(commit, /^[a-f0-9]{40}$/);
  assert.equal(new URL(map.url()).origin, new URL(info.baseUrl).origin);
  assert.equal(await map.locator('#graph-fallback').isVisible(), false);
  assert.ok(await map.locator('#graph-container canvas').count() > 0);
  checks.push('Admin login opens real native map on the same origin, with pinned full commit and WebGL canvas');
  await map.locator('#file-search').fill('invoice');
  assert.equal(await map.locator('#file-list button').count(), 1);
  await map.locator('#file-list button').click();
  await map.locator('#file-details').waitFor({ state: 'visible' });
  assert.ok((await map.locator('#source-code').textContent()).includes('createInvoice'));
  await map.locator('#dependencies').getByRole('button', { name: 'src/pricing.ts', exact: true }).click();
  await map.waitForFunction(() => document.getElementById('file-path').textContent === 'src/pricing.ts' && !document.getElementById('file-details').hidden);
  assert.ok((await map.locator('#source-code').textContent()).includes('fixture-v1'));
  assert.ok((await map.locator('#dependents').textContent()).includes('src/invoice.ts'));
  checks.push('All indexed files are searchable; dependency links navigate to matching commit source');
  const symbolCount = await map.locator('#symbol-list button').count(); assert.ok(symbolCount >= 2);
  await map.locator('#mode-symbols').click();
  assert.ok((await map.locator('#graph-caption').textContent()).includes(`${symbolCount} / ${symbolCount} 个符号`));
  await map.locator('.symbols summary').click();
  await map.locator('#symbol-search').fill('calculate');
  await map.locator('#symbol-list button').click();
  assert.ok((await map.locator('.code-line.highlight').textContent()).includes('calculatePrice'));
  assert.equal(await map.locator('.code-line.highlight').getAttribute('data-line'), '2');
  await map.locator('#zoom-in').click(); await map.locator('#reset-camera').click();
  await map.locator('#show-overview').click();
  assert.ok((await map.locator('#graph-caption').textContent()).includes('全库概览'));
  assert.equal(await map.locator('#file-path').textContent(), 'src/pricing.ts');
  await map.locator('#mode-symbols').click();
  assert.ok((await map.locator('#graph-caption').textContent()).includes(`${symbolCount} / ${symbolCount} 个符号`));
  assert.equal(await map.locator('#graph-fallback').isVisible(), false);
  checks.push('Native local symbols support source-line navigation and overview preserves current source selection');
  await map.screenshot({ path: fileURLToPath(new URL(`${prefix}-desktop.png`, evidence)), fullPage: true });
  await map.locator('#file-search').fill('markup'); await map.locator('#file-list button').click();
  await map.waitForFunction(() => !document.getElementById('file-details').hidden && document.getElementById('source-code').textContent.includes('<img src=x'));
  assert.equal(await map.evaluate(() => globalThis.viewerInjected), undefined);
  assert.equal(await map.locator('#source-code img').count(), 0);
  checks.push('Repository HTML is rendered as literal text without executing markup');
  await map.setViewportSize({ width: 390, height: 844 });
  await map.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await map.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await map.locator('#mode-symbols').click(); await map.locator('#reset-camera').click();
  await map.screenshot({ path: fileURLToPath(new URL(`${prefix}-mobile.png`, evidence)), fullPage: true });
  checks.push('390px mobile layout has no document overflow; reduced-motion controls remain usable');
  await page.locator('[data-close="detail-dialog"]').click();
  await page.getByRole('button', { name: '退出登录' }).click();
  await page.locator('#login-screen').waitFor({ state: 'visible' });
  await map.locator('#file-search').fill('pricing'); await map.locator('#file-list button').click();
  await map.locator('#map-workspace').waitFor({ state: 'hidden' });
  assert.equal(await map.locator('#source-code').textContent(), '');
  assert.equal(await map.locator('#file-list button').count(), 0);
  assert.equal(await map.locator('#repo-version').getAttribute('data-commit'), null);
  assert.equal(await map.locator('#graph-container canvas').count(), 0);
  checks.push('Logout denies map/source and removes private source, metadata, files and canvas from the open viewer');
  assert.deepEqual(errors, []); assert.deepEqual(externalRequests, []);
  checks.push('No JavaScript errors or external network requests; all graph libraries load locally');
  const report = { version: '0.2.0', environment: process.env.VIEWER_TEST_ENV || 'host service', checks, javascriptErrors: errors, externalRequests, pinnedCommit: commit, viewport: ['1600x1000', '390x844'], data: 'synthetic Git HTTP repository; native Codegraph graph, symbol and source data' };
  await fs.writeFile(new URL(prefix === 'map' ? 'viewer-ui-check.json' : `${prefix}-ui-check.json`, evidence), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
} finally { await browser.close(); }
